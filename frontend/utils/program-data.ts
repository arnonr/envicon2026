export interface GeneralScheduleSubItem {
  title: string;
  affiliation?: string;
}

export interface GeneralScheduleItem {
  time: string;
  title: string;
  speaker?: string;
  moderator?: string;
  bullets?: GeneralScheduleSubItem[];
  type: "registration" | "ceremony" | "keynote" | "panel" | "break" | "oral" | "poster" | "tour" | "dinner";
  oralBlockKey?: "oral1" | "oral2" | "oral3";
  isPosterBlock?: boolean;
  link?: string;
  linkText?: string;
}

export interface OralRoomTrack {
  id: string;
  sessionTitle: string;
  sessionSubtitle?: string;
  sessionCode: string;
  roomFloor: string;
  roomName: string;
  chair?: { name: string; affiliation: string };
  coChair?: { name: string; affiliation: string };
  isSpecialMeeting?: boolean;
  specialMeetingNote?: string;
  slots: Record<string, string>; // time -> paperCode or "-"
}

export interface OralSessionBlock {
  key: "oral1" | "oral2" | "oral3";
  dateLabel: string;
  timeRange: string;
  title: string;
  totalPapers: number;
  timeSlots: string[];
  rooms: OralRoomTrack[];
}

export interface PosterEvaluationColumn {
  id: string;
  sessionTitle: string;
  sessionCode: string;
  evaluators: { name: string; affiliation: string }[];
  paperCodes: string[];
}

export interface PosterSessionBlock {
  dateLabel: string;
  timeRange: string;
  title: string;
  totalPapers: number;
  columns: PosterEvaluationColumn[];
}

export interface PaperItem {
  order: number;
  code: string;
  title: string;
  author: string;
  type: "oral" | "poster";
}

export interface SessionTrackData {
  sessionNumber: number;
  code: string;
  nameTh: string;
  nameEn: string;
  colorClass: string;
  badgeClass: string;
  oralPapers: PaperItem[];
  posterPapers: PaperItem[];
}

export interface EnrichedPaperItem extends PaperItem {
  sessionNumber: number;
  sessionCode: string;
  sessionNameTh: string;
  sessionNameEn: string;
  dateLabel: string;
  timeSlot: string;
  roomLabel: string;
  chairOrEvaluators: string[];
}

