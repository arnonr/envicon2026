export function normalizePaperCode(code: string): string {
  return code.trim().toUpperCase().replace(/_/g, "-");
}

function buildScheduleIndex(): Map<
  string,
  { dateLabel: string; timeSlot: string; roomLabel: string; chairOrEvaluators: string[] }
> {
  const map = new Map<
    string,
    { dateLabel: string; timeSlot: string; roomLabel: string; chairOrEvaluators: string[] }
  >();

  for (const block of Object.values(oralSessionBlocks)) {
    for (const room of block.rooms) {
      if (room.isSpecialMeeting) continue;
      const chairs = [
        room.chair ? `Chair: ${room.chair.name}` : "",
        room.coChair ? `Co-chair: ${room.coChair.name}` : "",
      ].filter(Boolean);
      for (const [slot, code] of Object.entries(room.slots)) {
        if (code && code !== "-") {
          map.set(normalizePaperCode(code), {
            dateLabel: block.dateLabel,
            timeSlot: `${slot} น.`,
            roomLabel: `${room.roomFloor} ${room.roomName}`,
            chairOrEvaluators: chairs,
          });
        }
      }
    }
  }

  for (const col of posterSessionBlock.columns) {
    const evaluators = col.evaluators.map((e) => `ผู้ประเมิน: ${e.name}`);
    for (const code of col.paperCodes) {
      map.set(normalizePaperCode(code), {
        dateLabel: posterSessionBlock.dateLabel,
        timeSlot: `${posterSessionBlock.timeRange} น.`,
        roomLabel: "โถงจัดแสดงโปสเตอร์ อาคาร 99 อุทยานเทคโนโลยี มจพ.",
        chairOrEvaluators: evaluators,
      });
    }
  }

  return map;
}

const scheduleIndex = buildScheduleIndex();

export const allEnrichedPapers: EnrichedPaperItem[] = sessionTracks.flatMap((track) => {
  const combined = [...track.oralPapers, ...track.posterPapers];
  return combined.map((paper) => {
    const sched = scheduleIndex.get(normalizePaperCode(paper.code));
    return {
      ...paper,
      sessionNumber: track.sessionNumber,
      sessionCode: track.code,
      sessionNameTh: track.nameTh,
      sessionNameEn: track.nameEn,
      dateLabel: sched?.dateLabel ?? "12–13 พฤศจิกายน 2569",
      timeSlot: sched?.timeSlot ?? "-",
      roomLabel: sched?.roomLabel ?? "-",
      chairOrEvaluators: sched?.chairOrEvaluators ?? [],
    };
  });
});

const paperByNormalizedCode = new Map<string, EnrichedPaperItem>(
  allEnrichedPapers.map((p) => [normalizePaperCode(p.code), p]),
);

export function getPaperByCode(code: string): EnrichedPaperItem | undefined {
  return paperByNormalizedCode.get(normalizePaperCode(code));
}
